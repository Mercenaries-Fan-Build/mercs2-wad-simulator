/// One decoded frame: planes in 8-bit, Y full size, U and V at half size each way.
///
/// `y` is `width * height` bytes, row-major, no padding; `u` and `v` are
/// `((width + 1) / 2) * ((height + 1) / 2)` each, the visible area cropped out of the decoder's
/// padded planes (§7.1). U is Cb (plane B), V is Cr (plane A) (§1.5).
pub struct Frame {
    pub width: u32,
    pub height: u32,
    pub y: Vec<u8>,
    pub u: Vec<u8>,
    pub v: Vec<u8>,
}

/// The reader of §3: bit position `pos` in `data`, LSB first; reads may not pass `limit`.
struct Bits<'a> {
    data: &'a [u8],
    pos: usize,
    limit: usize,
}

impl<'a> Bits<'a> {
    /// A reader over `data[start..end]` (byte offsets).
    fn new(data: &'a [u8], start: usize, end: usize) -> Bits<'a> {
        Bits { data, pos: start * 8, limit: end * 8 }
    }

    /// The next `n` bits (`n <= 32`) without consuming them. Bytes past the data read as zero: a
    /// peek past the end only feeds a code-table lookup, and the codes are prefix codes (tested
    /// below), so those bits change the result only if the code is longer than what is left, and
    /// consuming it then fails.
    #[inline]
    fn peek(&self, n: u32) -> u32 {
        let at = self.pos >> 3;
        let window = match self.data.get(at..at + 8) {
            Some(b) => u64::from_le_bytes([b[0], b[1], b[2], b[3], b[4], b[5], b[6], b[7]]),
            None => {
                let mut w = [0u8; 8];
                let tail = self.data.get(at..).unwrap_or(&[]);
                w[..tail.len()].copy_from_slice(tail);
                u64::from_le_bytes(w)
            }
        };
        ((window >> (self.pos & 7)) & ((1u64 << n) - 1)) as u32
    }

    #[inline]
    fn skip(&mut self, n: u32) -> Result<(), String> {
        self.pos += n as usize;
        if self.pos > self.limit {
            return Err(format!("the plane's bits run past its end at byte {} (§1.5, §3)", self.limit / 8));
        }
        Ok(())
    }

    #[inline]
    fn bits(&mut self, n: u32) -> Result<u32, String> {
        let v = self.peek(n);
        self.skip(n)?;
        Ok(v)
    }

    #[inline]
    fn bit(&mut self) -> Result<bool, String> {
        Ok(self.bits(1)? == 1)
    }
}

/// One tree: a code table and its symbol map (§4.2).
#[derive(Clone, Copy)]
struct Tree {
    table: &'static [u8],
    maxlen: u32,
    map: [u8; 16],
}

/// `merge(A, B)` of §4.2.1: one bit per decision, A tested for exhaustion first.
fn merge(bits: &mut Bits, a: &[u8], b: &[u8], out: &mut [u8]) -> Result<(), String> {
    let (mut ia, mut ib, mut o) = (0, 0, 0);
    loop {
        if bits.bit()? {
            out[o] = b[ib];
            ib += 1;
        } else {
            out[o] = a[ia];
            ia += 1;
        }
        o += 1;
        if ia == a.len() {
            out[o..].copy_from_slice(&b[ib..]);
            return Ok(());
        }
        if ib == b.len() {
            out[o..].copy_from_slice(&a[ia..]);
            return Ok(());
        }
    }
}

impl Tree {
    /// The tree descriptor, `FUN_18013B60` (§4.2.1).
    fn read(bits: &mut Bits) -> Result<Tree, String> {
        let t = bits.bits(4)? as usize;
        let maxlen = TREE_MAXLEN[t];
        let table = &TREE_BYTES[TREE_OFF[t]..TREE_OFF[t] + (1 << maxlen)];
        let mut map = [0u8; 16];
        if t == 0 {
            for (i, m) in map.iter_mut().enumerate() {
                *m = i as u8;
            }
        } else if bits.bit()? {
            let k = bits.bits(3)? as usize;
            let mut unused: u32 = 0xffff;
            for m in map.iter_mut().take(k + 1) {
                let s = bits.bits(4)?;
                *m = s as u8;
                unused &= !(1 << s);
            }
            let mut at = k + 1;
            for sym in 0..16u8 {
                if at == 16 {
                    break;
                }
                if unused & (1 << sym) != 0 {
                    map[at] = sym;
                    at += 1;
                }
            }
        } else {
            let d = bits.bits(2)?;
            let mut p = [0u8; 16];
            for i in (0..16).step_by(2) {
                if bits.bit()? {
                    p[i] = i as u8 + 1;
                    p[i + 1] = i as u8;
                } else {
                    p[i] = i as u8;
                    p[i + 1] = i as u8 + 1;
                }
            }
            if d == 0 {
                map = p;
            } else {
                let mut q = [0u8; 16];
                for g in (0..16).step_by(4) {
                    merge(bits, &p[g..g + 2], &p[g + 2..g + 4], &mut q[g..g + 4])?;
                }
                match d {
                    1 => map = q,
                    2 => {
                        merge(bits, &q[0..4], &q[4..8], &mut map[0..8])?;
                        merge(bits, &q[8..12], &q[12..16], &mut map[8..16])?;
                    }
                    _ => {
                        let mut o = [0u8; 16];
                        merge(bits, &q[0..4], &q[4..8], &mut o[0..8])?;
                        merge(bits, &q[8..12], &q[12..16], &mut o[8..16])?;
                        merge(bits, &o[0..8], &o[8..16], &mut map)?;
                    }
                }
            }
        }
        Ok(Tree { table, maxlen, map })
    }

    /// One symbol (§4.2.3).
    #[inline]
    fn decode(&self, bits: &mut Bits) -> Result<u8, String> {
        let e = self.table[bits.peek(self.maxlen) as usize];
        bits.skip((e >> 4) as u32)?;
        Ok(self.map[(e & 15) as usize])
    }
}

/// The 23 trees of a plane header, in stream order (§4.1).
struct Trees {
    block: Tree,
    sub: Tree,
    colour_hi: [Tree; 16],
    colour_lo: Tree,
    pattern: Tree,
    mx: Tree,
    my: Tree,
    run: Tree,
}

impl Trees {
    fn read(bits: &mut Bits) -> Result<Trees, String> {
        let block = Tree::read(bits)?;
        let sub = Tree::read(bits)?;
        let first = Tree::read(bits)?;
        let mut colour_hi = [first; 16];
        for t in colour_hi.iter_mut().skip(1) {
            *t = Tree::read(bits)?;
        }
        Ok(Trees {
            block,
            sub,
            colour_hi,
            colour_lo: Tree::read(bits)?,
            pattern: Tree::read(bits)?,
            mx: Tree::read(bits)?,
            my: Tree::read(bits)?,
            run: Tree::read(bits)?,
        })
    }
}

/// `bitlen` of §4.3.
fn bitlen(x: usize) -> u32 {
    match x {
        0..=0x1ff => 9,
        0x200..=0x3ff => 10,
        0x400..=0x7ff => 11,
        0x800..=0xfff => 12,
        0x1000..=0x1fff => 13,
        0x2000..=0x3fff => 14,
        _ => 15,
    }
}

/// A bundle (§4.3). `cur`/`end` mirror the DLL's pointers as indices: terminated is `cur = 4,
/// end = 0`, so `cur != end` holds for the rest of the plane.
struct Bundle<T> {
    name: &'static str,
    buf: Vec<T>,
    cur: usize,
    end: usize,
    len_bits: u32,
}

impl<T: Copy + Default> Bundle<T> {
    fn new(name: &'static str, len_arg: usize, max: usize) -> Bundle<T> {
        Bundle { name, buf: vec![T::default(); max], cur: 0, end: 0, len_bits: bitlen(len_arg) }
    }

    /// The refill rule of §4.3: the count to decode now, or `None` when nothing is to be read.
    fn refill(&mut self, bits: &mut Bits) -> Result<Option<usize>, String> {
        if self.cur != self.end {
            return Ok(None);
        }
        let count = bits.bits(self.len_bits)? as usize;
        if count == 0 || count > self.buf.len() {
            self.cur = 4;
            self.end = 0;
            return Ok(None);
        }
        self.cur = 0;
        self.end = count;
        Ok(Some(count))
    }

    fn available(&self) -> bool {
        self.cur < self.end
    }

    #[inline]
    fn next(&mut self) -> Result<T, String> {
        if self.cur >= self.end {
            return Err(format!("the {} bundle is read past its end (§4.3)", self.name));
        }
        let v = self.buf[self.cur];
        self.cur += 1;
        Ok(v)
    }
}

/// The nine bundles of one plane (§4.3) and the colour context (§4.4.2).
struct Bundles {
    btype: Bundle<u8>,
    sub: Bundle<u8>,
    colour: Bundle<u8>,
    pattern: Bundle<u8>,
    mx: Bundle<i8>,
    my: Bundle<i8>,
    intra_dc: Bundle<i16>,
    inter_dc: Bundle<i16>,
    run: Bundle<u8>,
    prev_hi: u8,
}

/// Block types and sub-types, `FUN_18014260` (§4.4.1).
fn read_types(b: &mut Bundle<u8>, bits: &mut Bits, tree: &Tree) -> Result<(), String> {
    let Some(count) = b.refill(bits)? else { return Ok(()) };
    if bits.bit()? {
        let v = bits.bits(4)? as u8;
        b.buf[..count].fill(v);
        return Ok(());
    }
    let (mut i, mut last) = (0, 0u8);
    while i < count {
        let s = tree.decode(bits)?;
        if s < 12 {
            b.buf[i] = s;
            i += 1;
            last = s;
        } else {
            let r = RUN_LEN[s as usize - 12];
            if r > count - i {
                return Err(format!("a {} run of {r} past the bundle's {count} (§4.4.1)", b.name));
            }
            b.buf[i..i + r].fill(last);
            i += r;
        }
    }
    Ok(())
}

/// Motion x or y, `FUN_18014EF0` (§4.4.4).
fn read_motion(b: &mut Bundle<i8>, bits: &mut Bits, tree: &Tree) -> Result<(), String> {
    let Some(count) = b.refill(bits)? else { return Ok(()) };
    if bits.bit()? {
        let mut v = bits.bits(4)? as i8;
        if v != 0 && bits.bit()? {
            v = -v;
        }
        b.buf[..count].fill(v);
        return Ok(());
    }
    for e in &mut b.buf[..count] {
        let mut v = tree.decode(bits)? as i8;
        if v != 0 && bits.bit()? {
            v = -v;
        }
        *e = v;
    }
    Ok(())
}

/// Intra DC or inter DC, `FUN_18015130` (§4.4.5).
fn read_dc(b: &mut Bundle<i16>, bits: &mut Bits, signed: bool) -> Result<(), String> {
    let Some(count) = b.refill(bits)? else { return Ok(()) };
    let mut v: i32 = if signed {
        let m = bits.bits(10)? as i32;
        if m != 0 && bits.bit()? {
            -m
        } else {
            m
        }
    } else {
        bits.bits(11)? as i32
    };
    b.buf[0] = v as i16;
    let mut i = 1;
    while i < count {
        let g = (count - i).min(8);
        let w = bits.bits(4)?;
        for _ in 0..g {
            if w != 0 {
                let mut d = bits.bits(w)? as i32;
                if d != 0 && bits.bit()? {
                    d = -d;
                }
                v = v.wrapping_add(d);
            }
            b.buf[i] = v as i16;
            i += 1;
        }
    }
    Ok(())
}

impl Bundles {
    /// The bundles for a plane of decode width `w` (§4.3).
    fn new(w: usize) -> Bundles {
        let bw = w >> 3;
        let max = |x: usize| (x + 0x20f) & !15;
        Bundles {
            btype: Bundle::new("block type", bw + 511, max(bw)),
            sub: Bundle::new("sub-type", (w >> 4) + 511, max(w >> 4)),
            colour: Bundle::new("colour", bw * 64 + 511, max(bw * 64)),
            pattern: Bundle::new("pattern", bw * 8 + 511, max(bw * 8)),
            mx: Bundle::new("motion x", bw + 511, max(bw)),
            my: Bundle::new("motion y", bw + 511, max(bw)),
            intra_dc: Bundle::new("intra DC", bw + 511, ((bw * 2 + 0x40f) & !15) / 2),
            inter_dc: Bundle::new("inter DC", bw + 511, ((bw * 2 + 0x40f) & !15) / 2),
            run: Bundle::new("run", bw * 48 + 511, max(bw * 48)),
            prev_hi: 0,
        }
    }

    /// Every bundle empty and the colour context 0, as at the start of a plane (§4.1, §4.3).
    fn start_plane(&mut self) {
        self.btype.cur = 0;
        self.btype.end = 0;
        self.sub.cur = 0;
        self.sub.end = 0;
        self.colour.cur = 0;
        self.colour.end = 0;
        self.pattern.cur = 0;
        self.pattern.end = 0;
        self.mx.cur = 0;
        self.mx.end = 0;
        self.my.cur = 0;
        self.my.end = 0;
        self.intra_dc.cur = 0;
        self.intra_dc.end = 0;
        self.inter_dc.cur = 0;
        self.inter_dc.end = 0;
        self.run.cur = 0;
        self.run.end = 0;
        self.prev_hi = 0;
    }

    /// Colours, `FUN_180147F0` (§4.4.2).
    fn read_colours(&mut self, bits: &mut Bits, trees: &Trees) -> Result<(), String> {
        let Some(count) = self.colour.refill(bits)? else { return Ok(()) };
        let fill = bits.bit()?;
        let n = if fill { 1 } else { count };
        for i in 0..n {
            let hi = trees.colour_hi[self.prev_hi as usize].decode(bits)?;
            self.prev_hi = hi;
            let lo = trees.colour_lo.decode(bits)?;
            self.colour.buf[i] = (hi << 4) | lo;
        }
        if fill {
            let c = self.colour.buf[0];
            self.colour.buf[..count].fill(c);
        }
        Ok(())
    }

    /// Pattern, `FUN_18014CD0` (§4.4.3).
    fn read_pattern(&mut self, bits: &mut Bits, tree: &Tree) -> Result<(), String> {
        let Some(count) = self.pattern.refill(bits)? else { return Ok(()) };
        for e in &mut self.pattern.buf[..count] {
            let lo = tree.decode(bits)?;
            let hi = tree.decode(bits)?;
            *e = (hi << 4) | lo;
        }
        Ok(())
    }

    /// Run lengths, `FUN_18014AA0` (§4.4.6).
    fn read_runs(&mut self, bits: &mut Bits, tree: &Tree) -> Result<(), String> {
        let Some(count) = self.run.refill(bits)? else { return Ok(()) };
        if bits.bit()? {
            let v = bits.bits(4)? as u8;
            self.run.buf[..count].fill(v);
            return Ok(());
        }
        for e in &mut self.run.buf[..count] {
            *e = tree.decode(bits)?;
        }
        Ok(())
    }

    /// The per-row refill, in the DLL's order, then the motion-x index sync (§4.3).
    fn refill_row(&mut self, bits: &mut Bits, trees: &Trees) -> Result<(), String> {
        read_types(&mut self.btype, bits, &trees.block)?;
        read_types(&mut self.sub, bits, &trees.sub)?;
        self.read_colours(bits, trees)?;
        self.read_pattern(bits, &trees.pattern)?;
        read_motion(&mut self.mx, bits, &trees.mx)?;
        read_motion(&mut self.my, bits, &trees.my)?;
        read_dc(&mut self.intra_dc, bits, false)?;
        read_dc(&mut self.inter_dc, bits, true)?;
        self.read_runs(bits, &trees.run)?;
        self.mx.cur = self.my.cur;
        Ok(())
    }
}

/// Coefficient / residue list of §5.5 and §5.6.1: bytes `(k << 2) | mode`, 0 = empty slot.
/// Entries are prepended below `front` and appended at `back`.
struct List {
    e: [u8; 128],
    front: usize,
    back: usize,
}

const G20: u8 = 0;
const G16: u8 = 1;
const G4: u8 = 2;
const SINGLE: u8 = 3;

impl List {
    fn new(initial: &[u8]) -> List {
        let mut e = [0u8; 128];
        let front = 64;
        e[front..front + initial.len()].copy_from_slice(initial);
        List { e, front, back: front + initial.len() }
    }

    fn prepend(&mut self, k: usize, mode: u8) -> Result<(), String> {
        if self.front == 0 {
            return Err("a coefficient list grows past 64 prepended entries (§5.6.1)".into());
        }
        self.front -= 1;
        self.e[self.front] = ((k << 2) as u8) | mode;
        Ok(())
    }

    fn append(&mut self, k: usize, mode: u8) -> Result<(), String> {
        if self.back == self.e.len() {
            return Err("a coefficient list grows past its appended entries (§5.6.1)".into());
        }
        self.e[self.back] = ((k << 2) as u8) | mode;
        self.back += 1;
        Ok(())
    }

    /// `read_four(k)`: `set` is called for each coefficient sent now; it returns true to stop.
    fn read_four<F>(&mut self, bits: &mut Bits, k: usize, set: &mut F) -> Result<bool, String>
    where
        F: FnMut(&mut Bits, usize) -> Result<bool, String>,
    {
        for j in 0..4 {
            if bits.bit()? {
                self.prepend(k + j, SINGLE)?;
            } else if set(bits, k + j)? {
                return Ok(true);
            }
        }
        Ok(false)
    }

    /// One walk from the current front to the (growing) end. Returns true when `set` stopped it.
    fn walk<F>(&mut self, bits: &mut Bits, set: &mut F) -> Result<bool, String>
    where
        F: FnMut(&mut Bits, usize) -> Result<bool, String>,
    {
        let mut i = self.front;
        while i < self.back {
            let e = self.e[i];
            if e == 0 || !bits.bit()? {
                i += 1;
                continue;
            }
            let k = (e >> 2) as usize;
            match e & 3 {
                G20 => {
                    self.e[i] = (((k + 4) << 2) as u8) | G16;
                    if self.read_four(bits, k, set)? {
                        return Ok(true);
                    }
                }
                G16 => {
                    self.e[i] = ((k << 2) as u8) | G4;
                    self.append(k + 4, G4)?;
                    self.append(k + 8, G4)?;
                    self.append(k + 12, G4)?;
                }
                G4 => {
                    self.e[i] = 0;
                    i += 1;
                    if self.read_four(bits, k, set)? {
                        return Ok(true);
                    }
                }
                _ => {
                    self.e[i] = 0;
                    i += 1;
                    if set(bits, k)? {
                        return Ok(true);
                    }
                }
            }
        }
        Ok(false)
    }
}

/// DCT coefficients, `FUN_1801EFA0` (§5.6.1), placed by `PERM` into `c[1..64]` (§5.6.2).
fn read_coefficients(bits: &mut Bits, c: &mut [i32; 64]) -> Result<(), String> {
    let n = bits.bits(4)?;
    let mut t = [0i32; 64];
    let mut list = List::new(&[0x10, 0x60, 0xb0, 0x07, 0x0b, 0x0f]);
    for level in (1..=n).rev() {
        let top = 1i32 << (level - 1);
        list.walk(bits, &mut |bits: &mut Bits, k: usize| {
            let f = bits.bits(level)? as i32;
            let mag = top | (f & (top - 1));
            t[k] = if f & top != 0 { -mag } else { mag };
            Ok(false)
        })?;
    }
    for k in 1..64 {
        c[PERM[k]] = t[k];
    }
    Ok(())
}

/// Residue values in coding order, `FUN_1801F8E0` (§5.5); at most `m + 1` updates.
fn read_residue(bits: &mut Bits, m: u32) -> Result<[i8; 64], String> {
    let mut r = [0i8; 64];
    let b = bits.bits(3)?;
    let mut v: i32 = 1 << b;
    let mut list = List::new(&[0x10, 0x60, 0xb0, 0x02]);
    let mut nz = [0usize; 64];
    let mut nz_len = 0usize;
    let mut done = 0u32;
    for _ in 0..=b {
        for &idx in &nz[..nz_len] {
            if bits.bit()? {
                let step = if r[idx] < 0 { -v } else { v };
                r[idx] = r[idx].wrapping_add(step as i8);
                if done == m {
                    return Ok(r);
                }
                done += 1;
            }
        }
        let stopped = list.walk(bits, &mut |bits: &mut Bits, k: usize| {
            if nz_len == 64 {
                return Err("a residue sets more than 64 coefficients (§5.5)".into());
            }
            nz[nz_len] = k;
            nz_len += 1;
            r[k] = (if bits.bit()? { -v } else { v }) as i8;
            if done == m {
                return Ok(true);
            }
            done += 1;
            Ok(false)
        })?;
        if stopped {
            return Ok(r);
        }
        v >>= 1;
    }
    Ok(r)
}

type W = Wrapping<i32>;

/// `(a * k) >> 11` in 32-bit two's complement (§5.6.3).
#[inline]
fn mul11(a: W, k: i32) -> W {
    Wrapping((a * Wrapping(k)).0 >> 11)
}

/// The 1-D transform of §5.6.3.
#[inline]
fn idct8(e: [W; 8]) -> [W; 8] {
    let a = e[0] + e[4];
    let b = e[0] - e[4];
    let s = e[2] + e[6];
    let t = mul11(e[2] - e[6], 0xB50) - s;
    let (e0, e3, e1, e2) = (a + s, a - s, b + t, b - t);
    let u = e[5] + e[3];
    let v = e[5] - e[3];
    let w = e[1] + e[7];
    let x = e[1] - e[7];
    let o0 = u + w;
    let k = mul11(x + v, 0xEC8);
    let o1 = mul11(v, -0x14E8) - o0 + k;
    let o2 = mul11(w - u, 0xB50) - o1;
    let o3 = mul11(x, 0x8A9) - k + o2;
    [e0 + o0, e1 + o1, e2 + o2, e3 - o3, e3 + o3, e2 - o2, e1 - o1, e0 - o0]
}

/// Dequantise and transform (§5.6.3): the pass-2 outputs `z`, row-major, before rounding.
fn idct(c: &[i32; 64], q: &[i32; 64]) -> [W; 64] {
    let mut tmp = [Wrapping(0i32); 64];
    for col in 0..8 {
        let mut e = [Wrapping(0i32); 8];
        for (r, er) in e.iter_mut().enumerate() {
            *er = Wrapping((Wrapping(c[r * 8 + col]) * Wrapping(q[r * 8 + col])).0 >> 11);
        }
        let z = idct8(e);
        for r in 0..8 {
            tmp[r * 8 + col] = z[r];
        }
    }
    let mut out = [Wrapping(0i32); 64];
    for r in 0..8 {
        let mut e = [Wrapping(0i32); 8];
        e.copy_from_slice(&tmp[r * 8..r * 8 + 8]);
        out[r * 8..r * 8 + 8].copy_from_slice(&idct8(e));
    }
    out
}

/// The stored pixel of an intra transform: `((z + 0x7F) >> 8) & 0xFF`, no clamp (§5.6.3).
#[inline]
fn round_px(z: W) -> u8 {
    ((z + Wrapping(0x7F)).0 >> 8) as u8
}

/// Plane decode geometry (§2.2).
#[derive(Clone, Copy)]
struct Geo {
    w: usize,
    h: usize,
    pitch: usize,
}

fn put_block(dst: &mut [u8], off: usize, pitch: usize, blk: &[u8; 64]) {
    for r in 0..8 {
        dst[off + r * pitch..off + r * pitch + 8].copy_from_slice(&blk[r * 8..r * 8 + 8]);
    }
}

/// A scaled block: `B[r][c]` over the 2×2 pixels at `(2r, 2c)` (§5.2).
fn put_doubled(dst: &mut [u8], off: usize, pitch: usize, blk: &[u8; 64]) {
    for r in 0..8 {
        for i in 0..2 {
            let row = off + (2 * r + i) * pitch;
            for c in 0..8 {
                let p = blk[r * 8 + c];
                dst[row + 2 * c] = p;
                dst[row + 2 * c + 1] = p;
            }
        }
    }
}

fn copy_block(dst: &mut [u8], off: usize, src: &[u8], soff: usize, pitch: usize) {
    for r in 0..8 {
        dst[off + r * pitch..off + r * pitch + 8].copy_from_slice(&src[soff + r * pitch..soff + r * pitch + 8]);
    }
}

/// Run block into `blk` (§5.4).
fn run_block(bits: &mut Bits, bd: &mut Bundles, blk: &mut [u8; 64]) -> Result<(), String> {
    let scan = &SCAN[bits.bits(4)? as usize];
    let mut i = 0usize;
    let mut left = 64usize;
    loop {
        let r = bd.run.next()? as usize + 1;
        if left < r {
            return Err(format!("a run of {r} with {left} pixels left in a run block (§5.4)"));
        }
        left -= r;
        if bits.bit()? {
            let c = bd.colour.next()?;
            for _ in 0..r {
                blk[scan[i] as usize] = c;
                i += 1;
            }
        } else {
            for _ in 0..r {
                blk[scan[i] as usize] = bd.colour.next()?;
                i += 1;
            }
        }
        if left <= 1 {
            break;
        }
    }
    if i == 63 {
        blk[scan[63] as usize] = bd.colour.next()?;
    }
    Ok(())
}

/// Pattern block into `blk` (§5.9).
fn pattern_block(bd: &mut Bundles, blk: &mut [u8; 64]) -> Result<(), String> {
    let c0 = bd.colour.next()?;
    let c1 = bd.colour.next()?;
    for r in 0..8 {
        let p = bd.pattern.next()?;
        for k in 0..8 {
            blk[r * 8 + k] = if (p >> k) & 1 != 0 { c1 } else { c0 };
        }
    }
    Ok(())
}

/// Raw block into `blk` (§5.10).
fn raw_block(bd: &mut Bundles, blk: &mut [u8; 64]) -> Result<(), String> {
    for p in blk.iter_mut() {
        *p = bd.colour.next()?;
    }
    Ok(())
}

/// Intra block into `blk` (§5.6).
fn intra_block(bits: &mut Bits, bd: &mut Bundles, blk: &mut [u8; 64]) -> Result<(), String> {
    let mut c = [0i32; 64];
    c[0] = bd.intra_dc.next()? as i32;
    read_coefficients(bits, &mut c)?;
    let q = bits.bits(4)? as usize;
    let z = idct(&c, &QUANT_INTRA[q]);
    for (p, z) in blk.iter_mut().zip(z.iter()) {
        *p = round_px(*z);
    }
    Ok(())
}

/// The motion source of §5.3 as a linear offset, or `None` when out of range.
fn motion_src(geo: Geo, x: usize, y: usize, mx: i8, my: i8) -> Result<Option<usize>, String> {
    let p = geo.pitch as isize;
    let src = (y as isize + my as isize) * p + x as isize + mx as isize;
    let max = ((geo.h - 8) * geo.pitch + geo.w - 8) as isize;
    if src < 0 || src > max {
        return Ok(None);
    }
    let src = src as usize;
    if geo.pitch > geo.w && src % geo.pitch + 8 > geo.w {
        return Err(format!(
            "a motion vector reads the buffer's pitch padding (column {} of a {}-wide plane, pitch {}), whose content the spec leaves open (§5.3, §9.4)",
            src % geo.pitch,
            geo.w,
            geo.pitch
        ));
    }
    Ok(Some(src))
}

/// Everything one plane decode needs besides the bits.
struct PlaneOut<'a> {
    geo: Geo,
    dst: &'a mut [u8],
    refp: &'a [u8],
    ref_defined: bool,
    written: &'a mut Vec<bool>,
}

impl PlaneOut<'_> {
    fn need_ref(&self) -> Result<(), String> {
        if !self.ref_defined {
            return Err("a block reads the reference frame before any frame was decoded into it (§6, §9.4)".into());
        }
        Ok(())
    }

    fn mark(&mut self, x: usize, y: usize) {
        let bw = self.geo.w / 8;
        self.written[(y / 8) * bw + x / 8] = true;
    }
}

/// One plane, `FUN_18015500` (§2.3, §4, §5); the reader is left after the plane's last bit.
fn decode_plane(bits: &mut Bits, bd: &mut Bundles, out: &mut PlaneOut) -> Result<(), String> {
    let Geo { w, h, pitch } = out.geo;
    let trees = Trees::read(bits)?;
    bd.start_plane();
    out.written.clear();
    out.written.resize((w / 8) * (h / 8), false);
    let mut blk = [0u8; 64];
    for y in (0..h).step_by(8) {
        bd.refill_row(bits, &trees)?;
        let mut x = 0;
        while x < w {
            if !bd.btype.available() {
                x += 8;
                continue;
            }
            let t = bd.btype.next()?;
            let off = y * pitch + x;
            match t {
                0 => {
                    out.need_ref()?;
                    copy_block(out.dst, off, out.refp, off, pitch);
                    out.mark(x, y);
                    x += 8;
                }
                1 => {
                    if w - x < 16 {
                        x += 8;
                        continue;
                    }
                    if y & 8 != 0 || !bd.sub.available() {
                        x += 16;
                        continue;
                    }
                    let s = bd.sub.next()?;
                    if !matches!(s, 3 | 5 | 6 | 8 | 9) {
                        x += 16;
                        continue;
                    }
                    if h - y < 16 {
                        x += 8;
                        continue;
                    }
                    match s {
                        3 => run_block(bits, bd, &mut blk)?,
                        5 => intra_block(bits, bd, &mut blk)?,
                        6 => blk = [bd.colour.next()?; 64],
                        8 => pattern_block(bd, &mut blk)?,
                        _ => raw_block(bd, &mut blk)?,
                    }
                    put_doubled(out.dst, off, pitch, &blk);
                    out.mark(x, y);
                    out.mark(x + 8, y);
                    out.mark(x, y + 8);
                    out.mark(x + 8, y + 8);
                    x += 16;
                }
                2 => {
                    let mx = bd.mx.next()?;
                    let my = bd.my.next()?;
                    if let Some(src) = motion_src(out.geo, x, y, mx, my)? {
                        out.need_ref()?;
                        copy_block(out.dst, off, out.refp, src, pitch);
                        out.mark(x, y);
                    }
                    x += 8;
                }
                3 => {
                    run_block(bits, bd, &mut blk)?;
                    put_block(out.dst, off, pitch, &blk);
                    out.mark(x, y);
                    x += 8;
                }
                4 => {
                    let mx = bd.mx.next()?;
                    let my = bd.my.next()?;
                    if let Some(src) = motion_src(out.geo, x, y, mx, my)? {
                        out.need_ref()?;
                        let m = bits.bits(7)?;
                        let r = read_residue(bits, m)?;
                        for k in 0..64 {
                            let pos = PERM[k];
                            let o = (pos >> 3) * pitch + (pos & 7);
                            out.dst[off + o] = out.refp[src + o].wrapping_add(r[k] as u8);
                        }
                        out.mark(x, y);
                    }
                    x += 8;
                }
                5 => {
                    intra_block(bits, bd, &mut blk)?;
                    put_block(out.dst, off, pitch, &blk);
                    out.mark(x, y);
                    x += 8;
                }
                6 => {
                    blk = [bd.colour.next()?; 64];
                    put_block(out.dst, off, pitch, &blk);
                    out.mark(x, y);
                    x += 8;
                }
                7 => {
                    let mx = bd.mx.next()?;
                    let my = bd.my.next()?;
                    if let Some(src) = motion_src(out.geo, x, y, mx, my)? {
                        out.need_ref()?;
                        let mut c = [0i32; 64];
                        c[0] = bd.inter_dc.next()? as i32;
                        read_coefficients(bits, &mut c)?;
                        let q = bits.bits(4)? as usize;
                        let z = idct(&c, &QUANT_INTER[q]);
                        for r in 0..8 {
                            for col in 0..8 {
                                let o = r * pitch + col;
                                out.dst[off + o] = round_px(z[r * 8 + col]).wrapping_add(out.refp[src + o]);
                            }
                        }
                        out.mark(x, y);
                    }
                    x += 8;
                }
                8 => {
                    pattern_block(bd, &mut blk)?;
                    put_block(out.dst, off, pitch, &blk);
                    out.mark(x, y);
                    x += 8;
                }
                9 => {
                    raw_block(bd, &mut blk)?;
                    put_block(out.dst, off, pitch, &blk);
                    out.mark(x, y);
                    x += 8;
                }
                _ => x += 8,
            }
        }
    }
    Ok(())
}

/// Decodes a movie's video frames in order.
pub struct VideoDecoder {
    width: u32,
    height: u32,
    /// Y, V (plane A), U (plane B).
    geo: [Geo; 3],
    /// Two buffer sets of Y, V, U, each `pitch * height` (§6).
    sets: [[Vec<u8>; 3]; 2],
    /// Whether each plane of each set holds a decoded frame; until then its content is open (§9.4).
    defined: [[bool; 3]; 2],
    /// The set holding the last decoded frame (`[+0x14]`, §6).
    cur: usize,
    next_index: u32,
    luma: Bundles,
    chroma: Bundles,
    written: Vec<bool>,
    frame: Frame,
}

const PLANE_NAMES: [&str; 3] = ["Y", "V (plane A)", "U (plane B)"];

impl VideoDecoder {
    pub fn new(movie: &Movie) -> Result<VideoDecoder, String> {
        if movie.video_flags & FLAG_ALPHA != 0 {
            return Err(format!("video flags {:#x}: alpha planes are not supported; the spec reads them from code only (§1.5, §9.3)", movie.video_flags));
        }
        if movie.video_flags & FLAG_GRAYSCALE != 0 {
            return Err(format!("video flags {:#x}: grayscale movies are not supported; the spec reads them from code only (§1.5, §9.3)", movie.video_flags));
        }
        let (w, h) = (movie.width as usize, movie.height as usize);
        if w == 0 || h == 0 || w > 0x7fff || h > 0x7fff {
            return Err(format!("a {w}x{h} movie (§1.1: 1..=0x7fff each way)"));
        }
        let lw = (w + 7) & !7;
        let lh = (h + 7) & !7;
        let cw = (((w + 1) >> 1) + 7) & !7;
        let ch = (((h + 1) >> 1) + 7) & !7;
        let luma = Geo { w: lw, h: lh, pitch: lw };
        let chroma = Geo { w: cw, h: ch, pitch: (cw + 15) & !15 };
        let geo = [luma, chroma, chroma];
        let set = || [vec![0u8; lw * lh], vec![0u8; chroma.pitch * ch], vec![0u8; chroma.pitch * ch]];
        let (vw, vh) = (w.div_ceil(2), h.div_ceil(2));
        Ok(VideoDecoder {
            width: movie.width,
            height: movie.height,
            geo,
            sets: [set(), set()],
            defined: [[false; 3]; 2],
            cur: 0,
            next_index: 0,
            luma: Bundles::new(lw),
            chroma: Bundles::new(cw),
            written: Vec::new(),
            frame: Frame { width: movie.width, height: movie.height, y: vec![0; w * h], u: vec![0; vw * vh], v: vec![0; vw * vh] },
        })
    }

    /// Decode frame `index`'s video packet (`Movie::split(index).1`) and return the frame. Frames
    /// must come in order from 0: inter frames read the previous one.
    pub fn decode(&mut self, movie: &Movie, index: u32) -> Result<&Frame, String> {
        if index != self.next_index {
            return Err(format!("frame {index} asked for, but frames decode in order and the next is {}", self.next_index));
        }
        if movie.width != self.width || movie.height != self.height {
            return Err(format!("a {}x{} movie given to a decoder made for {}x{}", movie.width, movie.height, self.width, self.height));
        }
        let (_, video) = movie.split(index)?;
        // §1.5: Y size word (counting itself), Y, plane A, plane B at the word after A's last bit.
        let ysize = video
            .get(..4)
            .map(|b| u32::from_le_bytes([b[0], b[1], b[2], b[3]]) as usize)
            .ok_or_else(|| format!("frame {index}: a video packet of {} bytes has no Y size word (§1.5)", video.len()))?;
        if ysize < 4 || ysize > video.len() {
            return Err(format!("frame {index}: Y size {ysize} in a {}-byte video packet (§1.5)", video.len()));
        }
        let new = self.cur ^ 1;
        let mut start = 4usize;
        let mut end = ysize;
        for p in 0..3 {
            let mut bits = Bits::new(video, start, end);
            let geo = self.geo[p];
            let (lo, hi) = self.sets.split_at_mut(1);
            let (dst, refp) = if new == 1 { (&mut hi[0][p], &lo[0][p]) } else { (&mut lo[0][p], &hi[0][p]) };
            let mut out = PlaneOut { geo, dst, refp, ref_defined: self.defined[self.cur][p], written: &mut self.written };
            let bd = if p == 0 { &mut self.luma } else { &mut self.chroma };
            decode_plane(&mut bits, bd, &mut out).map_err(|e| format!("frame {index} plane {}: {e}", PLANE_NAMES[p]))?;
            if !self.defined[new][p] && out.written.iter().any(|w| !w) {
                return Err(format!(
                    "frame {index} plane {}: blocks left unwritten in a buffer no frame was decoded into; its content is open (§6, §9.4)",
                    PLANE_NAMES[p]
                ));
            }
            self.defined[new][p] = true;
            let used = bits.pos - start * 8;
            start = if p == 0 { ysize } else { start + 4 * used.div_ceil(32) };
            end = video.len();
        }
        self.cur = new;
        self.next_index += 1;
        let (w, h) = (self.width as usize, self.height as usize);
        let crop = |plane: &[u8], pitch: usize, cw: usize, ch: usize, out: &mut Vec<u8>| {
            for r in 0..ch {
                out[r * cw..r * cw + cw].copy_from_slice(&plane[r * pitch..r * pitch + cw]);
            }
        };
        let set = &self.sets[new];
        crop(&set[0], self.geo[0].pitch, w, h, &mut self.frame.y);
        let (vw, vh) = (w.div_ceil(2), h.div_ceil(2));
        crop(&set[1], self.geo[1].pitch, vw, vh, &mut self.frame.v);
        crop(&set[2], self.geo[2].pitch, vw, vh, &mut self.frame.u);
        Ok(&self.frame)
    }
}

