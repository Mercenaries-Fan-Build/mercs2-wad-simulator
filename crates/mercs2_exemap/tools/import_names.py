#!/usr/bin/env python3
"""import_names.py: build the import name tables of mercs2_exemap from their upstream sources.

    import_names.py xbox --xenia <dir> --xenia-commit <sha> --out <xbox_exports.tsv>
    import_names.py ps3 --rpcs3 <checkout> --rpcs3-commit <sha> --nids <nids.txt> \
        --nids-commit <sha> --out <ps3_fnid_names.tsv>

`xbox` converts Xenia's export tables (xam_table.inc, xboxkrnl_table.inc, xbdm_table.inc and
Xenia's LICENSE, all in <dir>, taken from the commit named) into rows of library, ordinal, name and
kind. The header carries Xenia's BSD-3 notice verbatim, the commit, and the git blob id of each
input file.

`ps3` writes every candidate PS3 PRX function name with the FNID it hashes to, from RPCS3 (every
REG_FUNC name and REG_FNID string in rpcs3/Emu/Cell/Modules/*.cpp, and every name of
ppu_get_function_name in rpcs3/Emu/Cell/PPUFunction.cpp whose FNID is its hash) and from
Ps3GhidraScripts' data/nids.txt (every pair whose FNID is its name's hash). Two names with one FNID
stop the script.

Every input line the script reads as a row must have the row's form; any other stops the script
naming the file and line. The output is sorted, so the same inputs give the same bytes.
"""
import argparse
import hashlib
import pathlib
import re
import struct
import sys

# Xenia's three export tables: the file, the module its XE_EXPORT rows name, the library name Xenia
# registers the table under (cited at the pinned commit), and that registration's source line.
XENIA_TABLES = [
    ("xam_table.inc", "xam", "xam.xex", "src/xenia/kernel/xam/xam_module.cc:61"),
    ("xboxkrnl_table.inc", "xboxkrnl", "xboxkrnl.exe", "src/xenia/kernel/xboxkrnl/xboxkrnl_module.cc:268"),
    ("xbdm_table.inc", "xbdm", "xbdm.xex", "src/xenia/kernel/xbdm/xbdm_module.cc:57"),
]
XENIA_TABLE_DIR = {"xam": "src/xenia/kernel/xam", "xboxkrnl": "src/xenia/kernel/xboxkrnl", "xbdm": "src/xenia/kernel/xbdm"}
XENIA_KIND = {"kFunction": "function", "kVariable": "variable"}
XE_EXPORT = re.compile(r"^XE_EXPORT\((\w+),\s*0x([0-9A-Fa-f]{8}),\s*(\w+),\s*(\w+)\),\s*$")

# RPCS3's FNID: the first 4 bytes, little-endian, of SHA-1(name || this suffix)
# (rpcs3/Emu/Cell/PPUModule.cpp, ppu_generate_id).
FNID_SUFFIX = bytes.fromhex("6759659904250490566427499489741A")
REG_FUNC = re.compile(r"\bREG_FUNC\(\s*\w+\s*,\s*(\w+)\s*\)")
REG_FNID_STRING = re.compile(r'\bREG_FNID\(\s*\w+\s*,\s*"([^"]+)"')
CASE_RETURN = re.compile(r'^\s*case (0x[0-9a-fA-F]{8}): return "([^"]+)";\s*$')
NIDS_ROW = re.compile(r"^0x([0-9A-Fa-f]{8}) (\S+)$")


def fail(msg):
    sys.exit(f"import_names.py: {msg}")


def git_blob(data):
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


def fnid(name):
    return struct.unpack("<I", hashlib.sha1(name.encode("ascii") + FNID_SUFFIX).digest()[:4])[0]


def commit_arg(s):
    if not re.fullmatch(r"[0-9a-f]{40}", s):
        raise argparse.ArgumentTypeError(f"{s!r} is not a 40-digit lowercase hex commit id")
    return s


def xbox(args):
    d = pathlib.Path(args.xenia)
    lic = (d / "LICENSE").read_bytes()
    out = []
    head = [
        "# The exports of the Xbox 360 system libraries, one row per library and ordinal, with Xenia's",
        "# name and kind for each (function: Xenia's kFunction; variable: Xenia's kVariable).",
        "# Generated by crates/mercs2_exemap/tools/import_names.py xbox from Xenia",
        f"# (https://github.com/xenia-project/xenia) commit {args.xenia_commit}:",
    ]
    notices = set()
    for fname, module, library, registered in XENIA_TABLES:
        data = (d / fname).read_bytes()
        head.append(f"#   {XENIA_TABLE_DIR[module]}/{fname} (git blob {git_blob(data)}) as {library},")
        head.append(f"#     the name Xenia registers it under ({registered})")
        seen = {}
        lines = data.decode("ascii").splitlines()
        for n, line in enumerate(lines, 1):
            if line.startswith(" * Copyright") or line.startswith(" * Released under"):
                notices.add(line[3:].rstrip(" *"))
            if "XE_EXPORT" not in line:
                continue
            m = XE_EXPORT.match(line)
            if not m:
                fail(f"{fname}:{n} is not XE_EXPORT(<module>, 0x<8 hex>, <name>, <kind>),: {line!r}")
            mod, ordinal, name, kind = m.group(1), int(m.group(2), 16), m.group(3), m.group(4)
            if mod != module:
                fail(f"{fname}:{n} names module {mod}, not {module}")
            if kind not in XENIA_KIND:
                fail(f"{fname}:{n} has kind {kind}, not kFunction or kVariable")
            if ordinal in seen:
                fail(f"{fname}:{n} repeats ordinal {ordinal} of line {seen[ordinal]}")
            seen[ordinal] = n
            out.append((library, ordinal, name, XENIA_KIND[kind]))
        if not seen:
            fail(f"{fname} has no XE_EXPORT row")
    head.append("#")
    head.append("# Each table file's notice:")
    for line in sorted(notices):
        head.append(f"#   {line}")
    head.append("#")
    head.append(f"# Xenia's LICENSE (git blob {git_blob(lic)}):")
    head.append("#")
    for line in lic.decode("ascii").splitlines():
        head.append(f"# {line}".rstrip())
    out.sort(key=lambda r: (r[0], r[1]))
    text = "\n".join(head) + "\nlibrary\tordinal\tname\tkind\n"
    text += "".join(f"{lib}\t{o}\t{name}\t{kind}\n" for lib, o, name, kind in out)
    pathlib.Path(args.out).write_text(text, encoding="ascii")
    print(f"{len(out)} exports -> {args.out}")


def ps3(args):
    root = pathlib.Path(args.rpcs3) / "rpcs3" / "Emu" / "Cell"
    names = {}  # name -> set of sources
    bad = {"PPUFunction.cpp": [], "nids.txt": []}

    def add(name, source):
        if not re.fullmatch(r"[\x21-\x7e]+", name):
            fail(f"{source}: name {name!r} is not printable ASCII without spaces")
        names.setdefault(name, set()).add(source)

    modules = sorted((root / "Modules").glob("*.cpp"))
    if not modules:
        fail(f"no rpcs3/Emu/Cell/Modules/*.cpp under {args.rpcs3}")
    for f in modules:
        text = f.read_text(encoding="utf-8")
        for m in REG_FUNC.finditer(text):
            add(m.group(1), f"Modules/{f.name}")
        for m in REG_FNID_STRING.finditer(text):
            add(m.group(1), f"Modules/{f.name}")

    ppuf = root / "PPUFunction.cpp"
    ppuf_bytes = ppuf.read_bytes()
    lines = ppuf_bytes.decode("utf-8").splitlines()
    start = [i for i, l in enumerate(lines) if l.startswith("extern std::string ppu_get_function_name(")]
    end = [i for i, l in enumerate(lines) if l.startswith("extern std::string ppu_get_variable_name(")]
    if len(start) != 1 or len(end) != 1 or end[0] <= start[0]:
        fail("PPUFunction.cpp does not define ppu_get_function_name once, before ppu_get_variable_name")
    pairs = 0
    for n in range(start[0], end[0]):
        line = lines[n]
        if "case 0x" not in line:
            continue
        m = CASE_RETURN.match(line)
        if not m:
            fail(f"PPUFunction.cpp:{n + 1} is not `case 0x<8 hex>: return \"<name>\";`: {line!r}")
        pairs += 1
        f, name = int(m.group(1), 16), m.group(2)
        if fnid(name) == f:
            add(name, "PPUFunction.cpp")
        else:
            bad["PPUFunction.cpp"].append((n + 1, f, name))

    nids_bytes = pathlib.Path(args.nids).read_bytes()
    nids_rows = 0
    for n, line in enumerate(nids_bytes.decode("ascii").splitlines(), 1):
        if not line.strip():
            continue
        m = NIDS_ROW.match(line)
        if not m:
            fail(f"nids.txt:{n} is not `0x<8 hex> <name>`: {line!r}")
        nids_rows += 1
        f, name = int(m.group(1), 16), m.group(2)
        if fnid(name) == f:
            add(name, "nids.txt")
        else:
            bad["nids.txt"].append((n, f, name))

    by_fnid = {}
    for name in names:
        f = fnid(name)
        if f in by_fnid:
            fail(f"FNID {f:08x} is the hash of both {by_fnid[f]!r} and {name!r}")
        by_fnid[f] = name

    for src, rows in bad.items():
        for n, f, name in rows:
            print(f"not listed: {src}:{n} pairs {f:08x} with {name!r}, whose hash is {fnid(name):08x}", file=sys.stderr)

    head = [
        "# Candidate PS3 PRX function names, one row per name, with the FNID the name hashes to:",
        "# the first 4 bytes, read little-endian, of SHA-1 of the name followed by the 16 bytes",
        "# 67 59 65 99 04 25 04 90 56 64 27 49 94 89 74 1A (RPCS3 rpcs3/Emu/Cell/PPUModule.cpp:58-75,",
        "# ppu_generate_id). mercs2_exemap recomputes every row's FNID when it loads the table; the",
        "# rows are names only, each proven by that hash.",
        "# Generated by crates/mercs2_exemap/tools/import_names.py ps3 from:",
        f"#   RPCS3 (https://github.com/RPCS3/rpcs3) commit {args.rpcs3_commit}: every REG_FUNC name and",
        f"#     REG_FNID string name in rpcs3/Emu/Cell/Modules/*.cpp ({len(modules)} files), and every",
        "#     `case 0x<fnid>: return \"<name>\"` of ppu_get_function_name in rpcs3/Emu/Cell/PPUFunction.cpp",
        f"#     (git blob {git_blob(ppuf_bytes)}) whose FNID is the name's hash ({pairs - len(bad['PPUFunction.cpp'])} of {pairs});",
        f"#   Ps3GhidraScripts (https://github.com/clienthax/Ps3GhidraScripts) commit {args.nids_commit}:",
        f"#     every `0x<fnid> <name>` row of data/nids.txt (git blob {git_blob(nids_bytes)}) whose FNID is",
        f"#     the name's hash ({nids_rows - len(bad['nids.txt'])} of {nids_rows}).",
        "fnid\tname",
    ]
    text = "\n".join(head) + "\n" + "".join(f"{f:08x}\t{by_fnid[f]}\n" for f in sorted(by_fnid))
    pathlib.Path(args.out).write_text(text, encoding="ascii")
    print(f"{len(by_fnid)} names -> {args.out}")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    x = sub.add_parser("xbox")
    x.add_argument("--xenia", required=True)
    x.add_argument("--xenia-commit", required=True, type=commit_arg)
    x.add_argument("--out", required=True)
    s = sub.add_parser("ps3")
    s.add_argument("--rpcs3", required=True)
    s.add_argument("--rpcs3-commit", required=True, type=commit_arg)
    s.add_argument("--nids", required=True)
    s.add_argument("--nids-commit", required=True, type=commit_arg)
    s.add_argument("--out", required=True)
    args = p.parse_args()
    {"xbox": xbox, "ps3": ps3}[args.cmd](args)


if __name__ == "__main__":
    main()
