function ResetSingleton(fCallback, tCallbackArgs)
  local function _PostDeleteLayers(nId)
    WifMissionFlow.Reset(true)
    
    MrxState.Reset()
    Graphics.SetShadowBaseDistance(10)
    Graphics.Camera.RestoreFocusParams(0, 1)
    Graphics.Camera.RestoreFovParams(0, 1)
    Graphics.Camera.RestoreNearFar(0)
    MrxGui:CleanupFadeFlash()
    MrxPlayer.Reset()
    MrxPlayer.Deinit()
    Pg.ResetSingletonDone()
    MrxUtil.CallWithOptionalArgs(fCallback, tCallbackArgs)
    Pg.UnloadingStaticLayers(false)
    if _fUnloadLayersCallback then
      _fUnloadLayersCallback(_tUnloadLayersCallbackData)
    end
  end
  
  MrxFactionManager.Reset()
  Pda:SetSuppressed({bSuppress = true})
  local tPlayers = Player.GetAllPlayers()
  for i, uPlayerGuid in ipairs(tPlayers) do
    local uCharacter = Player.GetCharacter(uPlayerGuid)
    Human.ForceExitSeatNoSnap(uCharacter)
  end
  if Net.IsClient() then
    MrxPmc.NetClientReimburse()
  end
  MrxState.Reset()
  MrxPlayState.Reset()
  MrxVoSequence.Reset()
  WifMissionFlow.Reset(true)
  MrxShootingGallery.Reset()
  MrxSoundBootstrap.ExitGame()
  local tStaticLayersCopy = {}
  local nLayerIndex, sLayerName
  for nLayerIndex, sLayerName in ipairs(_tStaticLayers) do
    table.insert(tStaticLayersCopy, sLayerName)
  end
  table.insert(tStaticLayersCopy, "vz_base")
  Pg.UnloadingStaticLayers(true)
  MrxLayerManager.RemoveAllLayers(tStaticLayersCopy, _PostDeleteLayers, {1})
  _tSaveState = nil
  _sSkipToMissionName = nil
  _tTeleportLocations = nil
end

function LoadSingleton(tSaveData)
  if Pg.GetUnloadingStaticLayers() then
    _fUnloadLayersCallback = LoadSingleton
    _tUnloadLayersCallbackData = tSaveData
    return
  end
  _fUnloadLayersCallback = nil
  _tUnloadLayersCallbackData = nil
  if not Net.IsMultiplayer() or Net.IsServer() then
    MrxPlayState.Reset()
    MrxPlayState.Set(MrxPlayState._knFree)
    _tSaveState = tSaveData
    if not _tSaveState and not _sSkipToMissionName then
      local sSkipToMissionName = Sys.GetSkipMission()
      Sys.SetSkipMission("")
      if type(sSkipToMissionName) == "string" and sSkipToMissionName ~= "" then
        _sSkipToMissionName = sSkipToMissionName
        _bSkipToBriefing = Sys.GetINIBriefing()
        MrxCheatBootstrap.EnableSkipMode(true, _sSkipToMissionName, _bSkipToBriefing)
      elseif Player.GetPlayerStart() ~= "PlayerLocation_Start" then
        _bAltSpawnLocation = true
      end
    end
    if _bAltSpawnLocation then
      _bLoadIntoWorld = true
    else
      local tStartLocations
      if _tSaveState then
        if Pg.LoadIsRetry() then
          tStartLocations = WifMissionFlow.GetRetryLocations()
        elseif _tSaveState.tRetryLocations then
          tStartLocations = _tSaveState.tRetryLocations
          WifMissionFlow.SetRetryLocations(tStartLocations)
          _bLoadIntoWorld = true
        else
          tStartLocations = {"Pmc_Entry1", "Pmc_Entry2"}
          _bPmcRequired = true
        end
      else
        local sMissionId
        if _sSkipToMissionName then
          sMissionId = _sSkipToMissionName
        else
          sMissionId = "VzaCon001"
        end
        if _sSkipToMissionName and _bSkipToBriefing then
          tStartLocations = WifMissionFlow.GetBriefingStartLocations(sMissionId)
        end
        tStartLocations = tStartLocations or WifMissionFlow.GetMissionStartLocations(sMissionId)
        tStartLocations = tStartLocations or {
          "Starter_Pmc_Start1",
          "Starter_Pmc_Start2"
        }
      end
      if type(tStartLocations) == "table" then
        if _bNewSession then
          MrxPlayer.SetSpawnLocations(tStartLocations)
        else
          _tTeleportLocations = tStartLocations
        end
      end
    end
  else
    Sys.SetSkipMission("")
  end
  if Pg.LoadIsRetry() then
    MrxState.Enter(MrxState.STATE_WAITFORSTREAMING, _LoadLayers, nil, _AttemptGameplaySetup, {"stream"})
  else
    _LoadLayers()
  end
end

function _LoadLayers()
  if not _bStaticLayersLoaded then
    MrxLayerManager.Add(_tStaticLayers, _AttemptGameplaySetup, {"static"}, true, true)
  end
  if not Net.IsMultiplayer() or Net.IsServer() then
    if Net.BeginLayerEventGroup then
      Net.BeginLayerEventGroup()
    end
    if _tSaveState then
      MrxLayerManager.LoadSingleton(_tSaveState.tLayerData, _AttemptGameplaySetup, {"dynamic"})
    else
      MrxLayerManager.Add(_tDefaultDynamicLayers, _AttemptGameplaySetup, {"dynamic"})
    end
  end
end

function _AttemptGameplaySetup(sSignal)
  local bProceed
  if sSignal == "boot" then
    _bBootstrapComplete = true
  elseif sSignal == "static" then
    _bStaticLayersLoaded = true
    MrxPlayer.Start()
  end
  bProceed = _bBootstrapComplete and _bStaticLayersLoaded
  if not Net.IsMultiplayer() or Net.IsServer() then
    if sSignal == "dynamic" then
      _bDynamicLayersLoaded = true
    end
    bProceed = bProceed and _bDynamicLayersLoaded
    if Pg.LoadIsRetry() then
      if sSignal == "stream" then
        _bInitialStreamComplete = true
      end
      bProceed = bProceed and _bInitialStreamComplete
    end
    if not bProceed then
      return
    end
    _bDynamicLayersLoaded = nil
    MrxState.Enter(MrxState.STATE_WAITFORGAME, _CompleteGameplaySetup)
    if _bInitialStreamComplete then
      MrxState.Exit(MrxState.STATE_WAITFORSTREAMING)
      _bInitialStreamComplete = nil
    end
  else
    if not bProceed then
      return
    end
    _GameplaySetup_LoadWorldState()
  end
end

function _CompleteGameplaySetup()
  _GameplaySetup_RestoreSubsystems()
  _GameplaySetup_LoadWorldState()
end

function _GameplaySetup_RestoreSubsystems()
  local tPlayers = Player.GetAllPlayers()
  for i, uPlayerGuid in ipairs(tPlayers) do
    local uCharacter = Player.GetCharacter(uPlayerGuid)
    Hero.EndSurvivalMode(uPlayerGuid, uCharacter, 0.1)
    Human.Inventory.ReloadAll(uCharacter, false)
    Human.SetState(uCharacter, "Upright", "Idle")
  end
  Pda.Support:SetEquippedItem({sName = nil, sId = nil})
  Sound.TransitionMusic("none")
  if _tSaveState then
    MrxPlayer.LoadSingleton(_tSaveState.tPlayerData)
  end
end

function _GameplaySetup_LoadWorldState()
  WifVzAmbience.Start()
  WifVzAtmosphere.Start()
  WifVZRegionNames.Start()
  if Net.IsClient() then
    Net.ApplyCachedFactionRelations()
    Net.SendEvent_RequestPosition()
    Debug.Printf("Loading client\n" .. tostring(_tSaveState) .. " cash=" .. tostring(Player.GetCash()) .. " fuel=" .. tostring(Player.GetFuel()))
    local bEnableCounters = WifMissionFlow.AreResourceCountersEnabled()
    WifMissionFlow.EnableResourceCounters(false)
    MrxPmc.DisplayResources()
    WifMissionFlow.EnableResourceCounters(bEnableCounters)
  end
  if not Net.IsMultiplayer() or Net.IsServer() then
    StagingAct1.Start()
    local bSetupBoundary = false
    if not _bAltSpawnLocation and not _sSkipToMissionName then
      bSetupBoundary = true
    end
    if _tSaveState then
      if bSetupBoundary then
        WifVzBoundary.LoadSingleton(_tSaveState.tBoundaryData, _bPmcRequired)
      end
      MrxPmc.LoadSingleton(_tSaveState.tPmcData)
      MrxSupportData.LoadSingleton(_tSaveState.tSupportData)
      MrxRewardData.LoadSingleton(_tSaveState.tRewardData)
      MrxFactionManager.LoadSingleton(_tSaveState.tFactionData)
      MrxTransit.LoadSingleton(_tSaveState.tTransitData)
      WifPmcInterior.LoadSingleton(_tSaveState.tPmcInteriorData)
      WifHints.LoadSingleton(_tSaveState.tActiveHint)
      WifBios.LoadSingleton(_tSaveState.tActiveBio)
      Munitions.LoadSingleton(_tSaveState.tMunitionsData)
      WifMissionFlow.SetGrappleEnabled(_tSaveState.bGrappleEnabled)
      WifMissionFlow.SetVehicleDisguiseEnabled(_tSaveState.bVehicleDisguiseEnabled)
      MrxTutorialManager.LoadSingleton(_tSaveState.tTutorialData)
      MrxShop.LoadSingleton(_tSaveState.tShopData)
      WifEquipmentData.LoadSingleton(_tSaveState.tWifEquipmentData)
      MrxAchievements.LoadSingleton(_tSaveState.tMrxAchievementsData)
      WifMissionFlow.SetLastCompletedContractName(_tSaveState.sLastMissionName)
      friendlygate.LoadSingleton(_tSaveState.tLockedGates)
      WifPmcInterior.SetAvailableCostumes(_tSaveState.nAvailableCostumes)
      WifMissionFlow.EnableResourceCounters(false)
      MrxPmc.DisplayResources()
      WifMissionFlow.EnableResourceCounters(_tSaveState.bResourceCountersEnabled)
      if _tSaveState.vEquippedSupport then
        Pda.Support:RestoreEquippedSupport({
          uPlayer = Player.GetPrimaryPlayer(),
          vSupport = _tSaveState.vEquippedSupport
        })
      end
    else
      if bSetupBoundary then
        WifVzBoundary.SetupBoundaryIntro()
      end
      MrxTransit.Reset()
      Munitions.SetMunitionsTaggable(false)
    end
    Debug.Printf("Loading Mission State....")
    Debug.Printf("*** Loading layers from task system activation")
    if _oMasterStub then
      _oMasterStub:Cleanup()
    end
    _oMasterStub = MrxTask:Create()
    _oMasterStub:Configure({sName = "Missions"})
    _oMasterStub:Activate()
    WifMissionFlow.Reset()
    WifMissionFlow.SetMissionParent(_oMasterStub)
    WifMissionFlow.SetPreContractSaveFunction(SetPreContractSaveData)
    MrxCheatBootstrap.SetTaskTreeRoot(_oMasterStub)
    MrxCheatBootstrap.SetMissionSkipDialogCallback(SkipToMission)
    if _tTeleportLocations then
      MrxUtil.TeleportHeroesToLocations(_tTeleportLocations, _SecondaryStreamComplete)
      _tTeleportLocations = nil
      if Pg.LoadIsRetry() then
        Event.Post("parkingLotStart", {false})
      end
      return
    end
  end
  MrxState.Enter(MrxState.STATE_WAITFORSTREAMING, nil, nil, _SecondaryStreamComplete)
end

function _SecondaryStreamComplete()
  MrxState.Exit(MrxState.STATE_WAITFORSTREAMING)
  _StartPlayerVisibleGameplay()
end

function _StartPlayerVisibleGameplay()
  Sound.TransitionMusic("none")
  if _tSaveState then
    WifMissionFlow.LoadSingleton(_tSaveState.tFlowData)
    MrxStarterManager.LoadSingleton(_tSaveState.tStarterData)
    MrxPlayState.SetTimeElapsedInPriorSessions(_tSaveState.nTimeElapsed)
    MrxStatsManager.LoadSingleton(_tSaveState.tStatsData)
    _tSaveState = nil
  else
    MrxPlayState.SetTimeElapsedInPriorSessions(0)
  end
  if not MrxPlayState.GetSessionTimer() then
    MrxPlayState.StartSessionTimer()
  end
  if not Net.IsMultiplayer() or Net.IsServer() then
    MrxStatsManager.DeleteWeaponTimer()
    MrxStatsManager.AddWeaponTimer()
  end
  if not _bAltSpawnLocation then
    WifMissionFlow.Refresh(MrxState.Exit, {
      MrxState.STATE_WAITFORGAME
    })
  else
    MrxState.Exit(MrxState.STATE_WAITFORGAME)
  end
  if Net.EndLayerEventGroup then
    Net.EndLayerEventGroup()
  end
  if _bPmcRequired then
    local function _EnterPmc()
      WifPmcInterior.SetLoadCallback(MrxState.Exit, {
        MrxState.STATE_WAITFORGAME
      })
      WifPmcInterior.Enter(true, 2)
    end
    
    if WifPmcInterior.IsInside() then
      WifPmcInterior.SetUnloadCallback(_EnterPmc)
      WifPmcInterior.Exit(1, true)
    else
      _EnterPmc()
    end
  end
  MrxTutorialManager.Setup()
  _bPmcRequired = nil
  _bLoadIntoWorld = nil
  _sSkipToMissionName = nil
  _bSkipToBriefing = nil
end

function SkipToMission(sMissionId, bBriefing)
  Sys.SetSkipMission(sMissionId)
  Sys.SetINIBriefing(bBriefing)
  Sys.RequestGameState("unloading")
end
