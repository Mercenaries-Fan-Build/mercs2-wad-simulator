  MrxVoSequence.Reset()
  MrxBootstrap.SetHandleStateTransitions(false)
  MrxBootstrap.Start(_AttemptGameplaySetup, {"boot"})
  if not Net.IsMultiplayer() or Net.IsServer() then
    MrxPlayer.Reset()
  end
