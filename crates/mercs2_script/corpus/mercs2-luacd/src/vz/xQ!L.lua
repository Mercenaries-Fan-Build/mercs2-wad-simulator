function SaveSingleton()
  Player.SetAvailableCostumes(WifPmcInterior.GetAvailableCostumes())
  local tSaveData
  tSaveData = GenerateSaveData()
  return tSaveData
end

nInGameCash = 0

function ClientReimburseForSave()
  if not Net.IsClient() then
    return
  end
  nInGameCash = Player.GetCash()
  local nTotalForSave
  nTotalForSave = nInGameCash + MrxPmc.GetClientReimburseAmount()
  Player.SetCash(nTotalForSave)
  Event.Create(Event.GameStateChange, {"Pause", "exit"}, ClientRestorePreSaveCash, {})
end

function ClientRestorePreSaveCash()
  if not Net.IsClient() then
    return
  end
  if nInGameCash then
    Player.SetCash(nInGameCash)
    nInGameCash = nil
  end
end

function SaveComplete()
  if _nOldCash then
    Player.SetCash(_nOldCash)
    _nOldCash = nil
  end
  if _nOldFuel then
    Player.SetFuel(_nOldFuel)
    _nOldFuel = nil
  end
end

