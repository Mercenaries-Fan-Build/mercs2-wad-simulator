                Chris = sVoBankName .. ".ChrisNeutralOnce01",
                Jennifer = sVoBankName .. ".JenNeutralOnce01",
                Mattias = sVoBankName .. ".MattiasNeutralOnce01"
              },
              Negative = {
                Chris = sVoBankName .. ".ChrisAngryOnce01",
                Jennifer = sVoBankName .. ".JenAngryOnce01",
                Mattias = sVoBankName .. ".MattiasAngryOnce01"
              }
            },
            Subsequent = {
              Positive = {
                sVoBankName .. ".Happy01",
                sVoBankName .. ".Happy02",
                sVoBankName .. ".Happy03"
              },
              Neutral = {
                sVoBankName .. ".Neutral01",
                sVoBankName .. ".Neutral02",
                sVoBankName .. ".Neutral03"
              },
              Negative = {
                sVoBankName .. ".Angry01",
                sVoBankName .. ".Angry02",
                sVoBankName .. ".Angry03"
              }
            }
          },
